import { expect, test } from '@playwright/test';

test('team task board creates assigns edits and completes a task on desktop and mobile', async ({ page }, testInfo) => {
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto('/login');
    await page.locator('input[name="email"]').fill('e2e@pitmetric.test');
    await page.locator('input[name="password"]').fill('PitMetric-E2E-2026!');
    await page.locator('form').filter({ has: page.locator('input[name="email"]') }).locator('button[type="submit"]').click();
    await expect(page).toHaveURL(/\/dashboard(?:\?|$)/);
    if (testInfo.project.name.includes('mobile')) await page.setViewportSize({ width: 320, height: 844 });
    await page.goto('/tasks');
    await page.locator('button[aria-controls="create-team-task"]').click();
    const create = page.locator('#create-team-task');
    const title = `Task board E2E ${testInfo.project.name}`;
    await create.locator('[name="event_id"]').selectOption({ index: 1 });
    await create.locator('[name="title"]').fill(title);
    await create.locator('[name="priority"]').selectOption('high');
    await create.locator('[name="assigned_to"]').selectOption({ index: 1 });
    await create.locator('[name="due_at"]').fill('2026-01-01T08:00');
    await create.locator('[name="description"]').fill('Check the kart before running.');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
    await create.locator('button[type="submit"]').click();
    const card = () => page.locator('[data-team-task]').filter({ hasText: title });
    await expect(card()).toBeVisible();
    await expect(card()).toContainText('PitMetric E2E');
    await card().locator('button[aria-controls^="edit-team-task-"]').click();
    const edit = page.locator('dialog[open][id^="edit-team-task-"]');
    await edit.locator('[name="description"]').fill('Updated from the task board.');
    await edit.locator('button[type="submit"]').click();
    await expect(card()).toContainText('Updated from the task board.');
    await card().locator('form:has(input[name="status"][value="in_progress"]) button').click();
    await page.goto('/tasks?bucket=in_progress');
    await expect(card()).toBeVisible();
    await card().locator('form:has(input[name="status"][value="done"]) button').click();
    await page.goto('/tasks?bucket=done');
    await expect(card()).toBeVisible();
    await expect(card()).toContainText('PitMetric E2E');
    await card().locator('summary').click();
    await expect(card().locator('details ol')).not.toBeEmpty();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
    await page.screenshot({ path: testInfo.outputPath('team-task-completed.png'), fullPage: true });
    await card().locator('form:has(input[name="status"][value="todo"]) button').click();
    await page.goto('/tasks?bucket=todo');
    await expect(card()).toBeVisible();
    expect(errors).toEqual([]);
});
